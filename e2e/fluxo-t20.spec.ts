import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, name: string) {
  await page.getByPlaceholder('Ex.: Ana').fill(name)
  await page.getByRole('button', { name: 'Entrar como convidado' }).click()
}

test('mestre prepara campanha T20, jogador cria ficha no assistente e passa o próprio turno', async ({ context }) => {
  const errors: string[] = []
  const gm = await context.newPage()
  gm.on('pageerror', (e) => errors.push(`[gm] ${e.message}`))
  await gm.goto('/')
  await login(gm, 'Mestre')
  await gm.getByRole('button', { name: 'Nova campanha' }).click()
  await gm.getByRole('textbox').first().fill('Ameaça em Valkaria')
  await gm.getByText('Incluir aventura de exemplo').click() // desmarca
  await gm.getByRole('button', { name: 'Criar e abrir a mesa' }).click()

  // saguão de preparação
  await expect(gm.getByText('Preparação do mestre')).toBeVisible()
  await expect(gm.getByText('Tormenta20 ·')).toBeVisible()
  await gm.getByPlaceholder(/Em Arton/).fill('Uma ameaça ronda a capital do Reinado.')
  await gm.getByPlaceholder(/Em Arton/).blur()
  const code = (await gm.getByTestId('invite-code').textContent())!.trim()
  await gm.screenshot({ path: 'test-results/20-saguao-mestre.png', fullPage: true })

  // jogador entra pelo convite e cria a ficha
  const pl = await context.newPage()
  pl.on('pageerror', (e) => errors.push(`[jogador] ${e.message}`))
  await pl.goto(`/convite/${code}`)
  await login(pl, 'Caio')
  await pl.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(pl.getByText('Uma ameaça ronda a capital do Reinado.')).toBeVisible()
  await pl.getByTestId('create-sheet').click()
  // raça → classe → origem → divindade → atributos → poderes → equipamento → aparência
  await pl.getByTestId('race-elfo').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('class-Arcanista').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('origin-estudioso').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('deity-wynna').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('auto-points').click()
  await expect(pl.getByTestId('points-left')).toContainText('Pontos restantes: 0')
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('power-Seta Infalível').click()
  await pl.getByTestId('power-Explosão de Chamas').click()
  await pl.getByTestId('power-Escudo Arcano').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('wizard-name').fill('Kael')
  await pl.screenshot({ path: 'test-results/20b-aparencia.png' })
  await pl.getByTestId('wizard-next').click()
  await pl.screenshot({ path: 'test-results/21-assistente-revisao.png' })
  await pl.getByTestId('wizard-create').click()
  await expect(pl.getByRole('dialog').locator('input[value="Kael"]')).toBeVisible()
  await pl.screenshot({ path: 'test-results/22-ficha-t20.png' })
  await pl.keyboard.press('Escape')
  await expect(gm.getByText('Kael (Elfo Arcanista 1)')).toBeVisible()
  // tudo o que foi escolhido ficou gravado na ficha
  const sheet = await pl.evaluate(() => (Object.values(JSON.parse(localStorage.getItem('mesa-arcana:characters') || '{}')).find((c: any) => c.name === 'Kael') as any).sheet)
  expect(sheet).toMatchObject({ race: 'Elfo', class: 'Arcanista', origin: 'Estudioso', deity: 'Wynna', level: 1 })
  expect(sheet.trained).toEqual(expect.arrayContaining(['misticismo', 'conhecimento', 'guerra']))
  expect(sheet.powers.map((p: any) => p.name)).toEqual(expect.arrayContaining(['Seta Infalível', 'Explosão de Chamas', 'Escudo Arcano']))
  expect(sheet.attrs.int).toBeGreaterThan(14)
  expect(sheet.pv_max).toBeGreaterThan(0)
  expect(sheet.bag.map((i: { name: string }) => i.name)).toContain('Livro raro')

  // mestre inicia a sessão; jogador entra na mesa
  await gm.getByTestId('start-session').click()
  await expect(gm.getByTestId('map-view')).toBeVisible()
  await expect(pl.getByText('Sessão 1 em andamento!')).toBeVisible()
  await pl.getByTestId('enter-table').click()
  await expect(pl.getByTestId('map-view')).toBeVisible()
  // jogador só vê Chat, Ficha e Magias
  await expect(pl.getByRole('tab', { name: 'Combate' })).toHaveCount(0)
  await pl.getByRole('tab', { name: 'Magias' }).click()
  await expect(pl.getByTestId('powers-panel').getByText('Seta Infalível')).toBeVisible()
  await expect(pl.getByTestId('powers-panel').getByText('Raio Congelante')).toHaveCount(0)
  // dados pelo botão central: 2d6 e tira um
  await pl.getByTestId('dice-fab').click()
  await pl.getByTestId('die-6').click()
  await pl.getByTestId('die-6').click()
  await pl.getByTestId('die-6').click()
  await pl.getByRole('button', { name: 'Remover d6' }).click()
  await expect(pl.getByTestId('roll-button')).toContainText('Lançar 2d6')
  await pl.getByTestId('roll-button').click()
  await expect(pl.getByTestId('roll-badge')).toBeVisible({ timeout: 20_000 })

  // mestre adiciona um goblin e inicia o combate
  await gm.getByRole('tab', { name: 'Fichas' }).click()
  await gm.getByRole('button', { name: 'Bestiário' }).click()
  await gm.locator('div', { hasText: /^Goblin/ }).getByRole('button', { name: 'Adicionar' }).first().click()
  await gm.getByRole('tab', { name: 'Combate' }).click()
  await gm.getByTestId('start-combat').click()
  await expect(gm.getByTestId('turn-bar')).toBeVisible()
  await expect(pl.getByTestId('turn-bar')).toBeVisible()

  // avança até ser a vez do Kael, e o jogador encerra o próprio turno
  const isKaelTurn = () => pl.getByRole('button', { name: 'Encerrar meu turno' }).isVisible()
  if (!(await isKaelTurn())) await gm.getByTestId('end-turn').click()
  await expect(pl.getByRole('button', { name: 'Encerrar meu turno' })).toBeVisible()
  await pl.screenshot({ path: 'test-results/23-sua-vez.png' })
  await pl.getByRole('button', { name: 'Encerrar meu turno' }).click()
  await expect(pl.getByRole('button', { name: 'Encerrar meu turno' })).toHaveCount(0)
  await pl.getByRole('tab', { name: 'Chat' }).click()
  await expect(pl.getByTestId('chat-log').getByText(/Vez de Goblin/).first()).toBeVisible()

  expect(errors).toEqual([])
})

test('campanha D&D: a ficha criada no assistente guarda todas as escolhas', async ({ context }) => {
  const gm = await context.newPage()
  await gm.goto('/')
  await login(gm, 'Mestre')
  await gm.getByRole('button', { name: 'Nova campanha' }).click()
  await gm.locator('select').first().selectOption('dnd5e')
  await gm.getByText('Incluir aventura de exemplo').click()
  await gm.getByRole('button', { name: 'Criar e abrir a mesa' }).click()
  const code = (await gm.getByTestId('invite-code').textContent())!.trim()
  const pl = await context.newPage()
  await pl.goto(`/convite/${code}`)
  await login(pl, 'Lia')
  await pl.getByRole('button', { name: 'Entrar', exact: true }).click()
  await pl.getByTestId('create-sheet').click()
  await pl.getByTestId('race-anao').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('class-Clérigo').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('origin-acolito').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('deity-lena').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('auto-points').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('power-Curar Ferimentos').click()
  await pl.getByTestId('power-Bênção').click()
  await pl.getByTestId('power-Luz Sagrada').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('wizard-name').fill('Brana')
  await pl.getByTestId('wizard-next').click()
  await pl.getByTestId('wizard-create').click()
  await expect(pl.getByRole('dialog').locator('input[value="Brana"]')).toBeVisible()
  const c = await pl.evaluate(() => Object.values(JSON.parse(localStorage.getItem('mesa-arcana:characters') || '{}')).find((x: any) => x.name === 'Brana') as any)
  expect(c.system_id).toBe('dnd5e')
  expect(c.sheet).toMatchObject({ race: 'Anão', class: 'Clérigo', background: 'Acólito', alignment: 'Devoto de Lena' })
  expect(c.sheet.spells.map((s: any) => s.name)).toEqual(expect.arrayContaining(['Curar Ferimentos', 'Bênção', 'Luz Sagrada']))
  expect(c.sheet.hp_max).toBeGreaterThan(0)
  expect(c.sheet.attacks.length).toBe(1)
  expect(c.sheet.skills.religiao).toBe(1)
})
